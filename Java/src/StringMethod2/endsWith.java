package StringMethod2;

public class endsWith {

	public static void main(String[] args) {
		String A="Nikhil";
		System.out.println(A.startsWith("Nik")); //true
		System.out.println(A.startsWith("N"));   //true
		System.out.println(A.endsWith("khil")); //true
		System.out.println(A.endsWith("l"));  //true
	}
}
